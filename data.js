function levelFromXp(xp){
  let level=1; let need=250; let left=xp;
  while(left>=need){left-=need;level++;need=Math.round(250*Math.pow(1.16,level-1));}
  const names=['Наблюдатель','Собиратель','Навигатор','Кодировщик','Нейронавигатор','Архивариус','Мнемонист','Картограф','Хранитель','Мастер следов'];
  return {level,name:names[Math.min(level-1,names.length-1)],current:left,need};
}
